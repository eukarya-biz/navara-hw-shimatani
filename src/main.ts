  // 夜明け・日暮れはなめらかに変化。これで昼に白飛びせず、夜は星がくっきり出る。
  const DAY_EXPOSURE = 10;
  const NIGHT_EXPOSURE = 32;
  function starExposureForMinutes(m: number): number {
    if (m >= 7 * 60 && m <= 17 * 60) return DAY_EXPOSURE; // 日中
    if (m >= 20 * 60 || m <= 4 * 60) return NIGHT_EXPOSURE; // 夜
    if (m > 4 * 60 && m < 7 * 60) {
      // 夜明け(4:00夜→7:00昼)
      const t = (m - 4 * 60) / (3 * 60);
      return NIGHT_EXPOSURE + (DAY_EXPOSURE - NIGHT_EXPOSURE) * t;
    }
    // 日暮れ(17:00昼→20:00夜)
    const t = (m - 17 * 60) / (3 * 60);
    return DAY_EXPOSURE + (NIGHT_EXPOSURE - DAY_EXPOSURE) * t;
  }
