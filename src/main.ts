  /** 条件が持つ基準時刻を「その日の何分目か(0〜1439)」に変換する */
  function minutesOf(dateTimeIso: string): number {
    const hh = Number(dateTimeIso.slice(11, 13));
    const mm = Number(dateTimeIso.slice(14, 16));
    return hh * 60 + mm;
  }

  /** 分(0〜1439)を"HH:MM"表示に変換する */
  function formatMinutes(totalMinutes: number): string {
    const hh = Math.floor(totalMinutes / 60)
      .toString()
      .padStart(2, "0");
    const mm = (totalMinutes % 60).toString().padStart(2, "0");
    return `${hh}:${mm}`;
  }

