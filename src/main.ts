    timeLabel.textContent = `${spot.name} / 時刻: ${formatMinutes(minutesOf(condition.dateTimeIso))}`;
    noteLabel.textContent = condition.note ?? "";
    updateStarExposure(minutesOf(condition.dateTimeIso)); // 星空地点の露出を反映
    // 星空以外で露出を固定したい地点(逆光の富士など)は、その値を適用する
